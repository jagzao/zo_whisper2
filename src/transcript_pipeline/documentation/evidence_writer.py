"""Evidence Plane writers (SPEC §10, PLAN WP-03).

Moves the frame-by-frame human representation from the manual to the
evidence directory:

- evidence/evidence.jsonl         — one EvidenceItem per line;
- evidence/EVIDENCE_TIMELINE.md   — raw chronological captured evidence
                                    (the old frame-by-frame representation);
- evidence/review-queue.json      — low/no-evidence placeholders.

EVIDENCE_TIMELINE.pdf is NOT generated by default (SPEC §10). The legacy
manual/steps.json compatibility source keeps being written by the engine.
"""
from __future__ import annotations

import json
from pathlib import Path

from transcript_pipeline.documentation.evidence import EvidenceTimeline


def format_timestamp(seconds: float) -> str:
    h, r = divmod(int(seconds), 3600)
    m, s = divmod(r, 60)
    return f"{h:02d}:{m:02d}:{s:02d}"


def write_evidence_outputs(frames_dir: Path, timeline: EvidenceTimeline) -> dict[str, Path]:
    """Writes the durable evidence artifacts under `<frames_dir>/evidence/`.

    Source frames and frame_mapping.json are never touched (SPEC §5.10)."""
    evidence_dir = frames_dir / "evidence"
    evidence_dir.mkdir(parents=True, exist_ok=True)

    jsonl_path = evidence_dir / "evidence.jsonl"
    jsonl_path.write_text(
        "".join(json.dumps(item.to_dict(), ensure_ascii=False) + "\n" for item in timeline.items),
        encoding="utf-8",
    )

    md_path = evidence_dir / "EVIDENCE_TIMELINE.md"
    md_path.write_text(_render_timeline_md(timeline), encoding="utf-8")

    queue_path = evidence_dir / "review-queue.json"
    queue_path.write_text(
        json.dumps(
            {
                "schemaVersion": 2,
                "reviewRequiredCount": timeline.review_required_count,
                "items": [item.to_dict() for item in timeline.review_queue],
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    return {"evidence": jsonl_path, "timeline": md_path, "review_queue": queue_path}


def _render_timeline_md(timeline: EvidenceTimeline) -> str:
    lines = [
        f"# Evidence Timeline — {timeline.source_media}\n\n",
        f"- Duration: {format_timestamp(timeline.duration)} ({timeline.duration:.0f}s)\n",
        f"- Language: {timeline.language}\n",
        f"- Evidence fidelity: {timeline.fidelity}\n",
        f"- Evidence items: {timeline.item_count}\n",
        f"- Review-required items: {timeline.review_required_count}\n\n",
        "> This is the immutable Evidence Plane: every captured moment in\n"
        "> chronological order. It is NOT the human manual — see manual/MANUAL.md\n"
        "> for the semantic, evidence-grounded documentation.\n\n---\n\n",
    ]
    for item in timeline.items:
        ts = (
            "untimed"
            if item.untimed
            else f"{format_timestamp(item.timestamp_start)}–{format_timestamp(item.timestamp_end)}"
        )
        lines.append(f"## {item.evidence_id} @ {ts}\n\n")
        lines.append(
            f"`source: {item.evidence_source}` · `confidence: {item.confidence}`"
            f"{' · ✓ reviewed' if item.reviewed else ''}\n\n"
        )
        if item.frame_ref:
            lines.append(f"- Frame: `{item.frame_ref}`\n")
        if item.transcript_excerpt:
            lines.append(f"- Transcript: {item.transcript_excerpt}\n")
        if item.ocr_excerpt:
            lines.append(f"- OCR: {item.ocr_excerpt}\n")
        if item.is_placeholder():
            lines.append(
                "- No captured evidence near this moment — queued for human review.\n"
            )
        lines.append(f"- Provenance: {item.source_provenance}\n\n")
    return "".join(lines)
