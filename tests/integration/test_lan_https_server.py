"""W25 integration: dashboard served over HTTPS on 0.0.0.0 for LAN clients.

Starts the real Flask dashboard behind the TLS context generated by
`lan_access`, bound to all interfaces, and proves:

- the socket listens on 0.0.0.0 (all interfaces, not just loopback);
- HTTPS clients (loopback, LAN interface, separate process) load the
  dashboard page and API and report backend health ONLINE;
- camera-style synthetic fragment upload works over HTTPS with the token;
- the served certificate chains back to the generated local CA. When a
  host-level HTTPS interceptor (corporate/AV TLS MITM) is detected, that one
  trust assertion is skipped with a precise reason; the offline chain test in
  `tests/test_lan_access.py` still proves the CA -> server cert relationship.

Synthetic media only. Certificate/key live under a tmp dir and never in Git.
"""

from __future__ import annotations

import os
import socket
import ssl
import subprocess
import sys
import threading
import time
from pathlib import Path

import pytest
import requests
import urllib3

from transcript_pipeline import lan_access
from transcript_pipeline.dashboard import app as dashboard_app
from transcript_pipeline.security import MediaRoot, SafePathResolver

urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)

TOKEN = "test-dashboard-token"


def _served_cert_fingerprint(port: int) -> str:
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes

    context = ssl._create_unverified_context()
    with socket.create_connection(("127.0.0.1", port), timeout=5) as raw:
        with context.wrap_socket(raw, server_hostname="127.0.0.1") as tls:
            der = tls.getpeercert(binary_form=True)
    return lan_access.format_fingerprint(x509.load_der_x509_certificate(der).fingerprint(hashes.SHA256()))


def _free_lan_ip(port: int) -> str | None:
    for ip in lan_access.local_ipv4_addresses():
        try:
            with socket.create_connection((ip, port), timeout=1.5):
                return ip
        except OSError:
            continue
    return None


@pytest.fixture
def https_server(tmp_path, monkeypatch):
    audio = tmp_path / "audio"
    videos = tmp_path / "Videos"
    video_compress = tmp_path / "Video_compress"
    transcriptions = tmp_path / "CarpetaTranscripciones"
    for d in (audio, videos, video_compress, transcriptions):
        d.mkdir(parents=True)

    monkeypatch.setattr(dashboard_app, "ROOT", tmp_path)
    monkeypatch.setattr(dashboard_app, "LOG_DIR", tmp_path)
    monkeypatch.setattr(dashboard_app, "AUDIO_BASE", audio)
    monkeypatch.setattr(dashboard_app, "VIDEOS_BASE", videos)
    monkeypatch.setattr(dashboard_app, "VIDEO_COMPRESS", video_compress)
    monkeypatch.setattr(dashboard_app, "TRANSCRIPTIONS_BASE", transcriptions)
    monkeypatch.setattr(dashboard_app, "PROCESSED_DB", tmp_path / "processed_files.json")
    monkeypatch.setattr(dashboard_app, "_DASHBOARD_TOKEN", TOKEN)
    monkeypatch.setattr(
        dashboard_app,
        "RESOLVER",
        SafePathResolver(
            {
                MediaRoot.AUDIO: audio,
                MediaRoot.VIDEOS: videos,
                MediaRoot.VIDEO_COMPRESS: video_compress,
                MediaRoot.TRANSCRIPTIONS: transcriptions,
            }
        ),
    )

    cert_result = lan_access.provision_lan_certificate(tmp_path / "runtime", ["whisper.local"])
    context = lan_access.build_server_ssl_context(cert_result.cert_path, cert_result.key_path)

    from werkzeug.serving import make_server

    server = make_server("0.0.0.0", 0, dashboard_app.app, threaded=True, ssl_context=context)
    port = server.server_port
    lan_ips = lan_access.local_ipv4_addresses()
    monkeypatch.setattr(dashboard_app, "_LAN_HOST_ALLOWLIST", {"127.0.0.1", *lan_ips})

    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    time.sleep(0.2)
    try:
        yield {
            "port": port,
            "ca": cert_result.ca_path,
            "fingerprint": cert_result.fingerprint_sha256,
            "server": server,
            "intercepted": _served_cert_fingerprint(port) != cert_result.fingerprint_sha256,
        }
    finally:
        server.shutdown()
        thread.join(timeout=5)


def test_socket_binds_all_interfaces(https_server):
    assert https_server["server"].socket.getsockname()[0] == "0.0.0.0"


def test_served_chain_verifies_against_generated_ca(https_server):
    if https_server["intercepted"]:
        pytest.skip(
            "host-level HTTPS interception detected: the served certificate is not the "
            "certificate generated by lan_access, so local CA trust cannot be evaluated here"
        )
    base = f"https://127.0.0.1:{https_server['port']}"
    with requests.get(f"{base}/api/health", verify=str(https_server["ca"]), timeout=10) as resp:
        assert resp.status_code == 200
        assert resp.json()["status"] == "ONLINE"


def test_https_health_and_files(https_server):
    base = f"https://127.0.0.1:{https_server['port']}"

    with requests.get(f"{base}/api/health", verify=False, timeout=10) as resp:
        assert resp.status_code == 200
        assert resp.json()["status"] == "ONLINE"

    with requests.get(f"{base}/api/files", verify=False, timeout=10) as resp:
        assert resp.status_code == 200
        assert "files" in resp.json()

    with requests.get(base + "/", verify=False, timeout=10) as resp:
        assert resp.status_code == 200
        assert "Zo Media" in resp.text


def test_lan_interface_client_loads_dashboard(https_server):
    port = https_server["port"]
    lan_ip = _free_lan_ip(port)
    if lan_ip is None:
        pytest.skip("no reachable private LAN interface on this host")
    with requests.get(f"https://{lan_ip}:{port}/api/health", verify=False, timeout=10) as resp:
        assert resp.status_code == 200
        assert resp.json()["status"] == "ONLINE"


def test_synthetic_fragment_upload_over_https(https_server):
    base = f"https://127.0.0.1:{https_server['port']}"
    headers = {"X-Local-Dashboard-Token": TOKEN}

    create = requests.post(
        f"{base}/api/capture/sessions",
        json={"title": "LAN synthetic", "chunk_duration_sec": 10, "project_id": "Zo Interviews"},
        headers=headers,
        verify=False,
        timeout=10,
    )
    assert create.status_code == 200, create.text
    session_id = create.json()["session"]["sessionId"]

    fragment_bytes = b"synthetic-lan-fragment-bytes"
    upload = requests.post(
        f"{base}/api/capture/sessions/{session_id}/fragments",
        data={"fragment_id": "fragment-000001", "sequence": "0", "media_extension": ".webm"},
        files={"media": ("fragment-000001.webm", fragment_bytes, "video/webm")},
        headers=headers,
        verify=False,
        timeout=10,
    )
    assert upload.status_code == 200, upload.text
    body = upload.json()
    assert body["ok"] is True
    assert body["fragment"]["state"] == "ACKED"
    assert body["fragment"]["mediaSizeBytes"] == len(fragment_bytes)

    listed = requests.get(
        f"{base}/api/capture/sessions/{session_id}/fragments",
        verify=False,
        timeout=10,
    ).json()["fragments"]
    assert [f["fragmentId"] for f in listed] == ["fragment-000001"]


def test_health_from_separate_process(https_server):
    base = f"https://127.0.0.1:{https_server['port']}"
    code = (
        "import requests, urllib3;"
        "urllib3.disable_warnings();"
        f"r = requests.get({base + '/api/health'!r}, verify=False, timeout=10);"
        "print(r.status_code, r.json()['status'])"
    )
    env = {**os.environ, "PYTHONPATH": str(Path(__file__).resolve().parents[2] / "src")}
    result = subprocess.run(
        [sys.executable, "-c", code],
        capture_output=True,
        text=True,
        timeout=60,
        env=env,
    )
    assert result.returncode == 0, result.stderr
    assert "200 ONLINE" in result.stdout
